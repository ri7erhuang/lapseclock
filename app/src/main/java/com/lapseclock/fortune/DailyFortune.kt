/** 同一天永远是同一签：按 epochDay 取模，不用随机数 */
fun fortuneOf(date: LocalDate): Fortune {
    val size = FORTUNES.size
    val idx = (date.toEpochDay() % size).toInt()
    return FORTUNES[if (idx < 0) idx + size else idx]
}
